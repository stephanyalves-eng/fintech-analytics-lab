"""Data provenance labels and deterministic random generators."""

from __future__ import annotations

import platform
from enum import StrEnum
from importlib import metadata

import numpy as np


class DataOrigin(StrEnum):
    """Origin label required on every dataset/table."""

    OBSERVED = "observed"
    SYNTHETIC = "synthetic"
    DERIVED = "derived"


def make_rng(seed: int) -> np.random.Generator:
    """Return a reproducible NumPy generator. Seed must be a non-negative int."""
    if not isinstance(seed, int) or isinstance(seed, bool) or seed < 0:
        raise ValueError(f"seed must be a non-negative int, got {seed!r}")
    return np.random.default_rng(seed)


RUNTIME_PACKAGES = ("numpy", "pandas", "pyarrow", "duckdb", "pyyaml", "scipy")


def environment(packages: tuple[str, ...] = RUNTIME_PACKAGES) -> dict[str, str]:
    """Python, OS and library versions that determine generated bytes (for manifests)."""
    env = {"python": platform.python_version(), "platform": platform.platform()}
    for name in packages:
        try:
            env[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            env[name] = "not installed"
    return env
