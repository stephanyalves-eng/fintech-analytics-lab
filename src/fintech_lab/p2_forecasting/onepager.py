"""Executive one-pager (self-contained HTML, print-friendly) generated from computed values only."""

from __future__ import annotations

import html
import json
from pathlib import Path
from typing import Any

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[3]


def _tokens() -> dict[str, Any]:
    p = REPO_ROOT / "shared" / "design_tokens" / "tokens.json"
    return json.loads(p.read_text(encoding="utf-8"))


def _bars(rows: list[tuple[str, float, str]], width: int = 520) -> str:
    """Horizontal bars as inline SVG; labels carry the values, so colour is not the only channel."""
    top = max(v for _, v, _ in rows) or 1.0
    h, gap, left = 22, 8, 150
    out = [f'<svg role="img" aria-label="TPV by plan and actual" width="{width}" '
           f'height="{len(rows) * (h + gap)}" viewBox="0 0 {width} {len(rows) * (h + gap)}">']
    for i, (name, v, color) in enumerate(rows):
        y = i * (h + gap)
        w = (width - left - 90) * v / top
        out.append(f'<text x="0" y="{y + 16}" font-size="12">{html.escape(name)}</text>'
                   f'<rect x="{left}" y="{y}" width="{w:.1f}" height="{h}" fill="{color}"/>'
                   f'<text x="{left + w + 6:.1f}" y="{y + 16}" font-size="12">'
                   f'{v / 1e6:.2f}M</text>')
    out.append("</svg>")
    return "".join(out)


def _table(df: pd.DataFrame, fmt: dict[str, str]) -> str:
    head = "".join(f"<th>{html.escape(str(c))}</th>" for c in df.columns)
    body = ""
    for _, r in df.iterrows():
        cells = ""
        for c in df.columns:
            v = r[c]
            f = fmt.get(c)
            cells += f"<td>{html.escape(f.format(v) if f and v == v else str(v))}</td>"
        body += f"<tr>{cells}</tr>"
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def build_onepager(o: dict[str, Any], meta: dict[str, Any]) -> str:
    tk = _tokens()["color"]
    h = o["headline"].set_index("metric")
    cmp_ = o["budget_cmp"]
    tpv = h.loc["TPV"]
    cards = ""
    for name in ("TPV", "Net revenue", "Contribution margin"):
        r = h.loc[name]
        cards += (f'<div class="card"><div class="lbl">{name}</div>'
                  f'<div class="val">{r.actual / 1e6:.2f}M</div>'
                  f'<div class="sub">vs budget v1 {r.actual_vs_budget_pct:+.1%} · '
                  f'vs forecast {r.actual_vs_forecast_pct:+.1%}</div></div>')
    bars = [("Actual", float(tpv.actual), tk["primary"] if "primary" in tk else "#2a78d6"),
            ("Budget v1", float(tpv.budget), "#8a8f98"),
            ("Forecast (composed)", float(tpv.forecast_composed), "#eb6834")]
    if cmp_ is not None:
        bars.insert(2, ("Budget v2 (30/09)", float(cmp_.iloc[0].budget_v2), "#5b6573"))
    br = o["budget_to_actual"]
    br = br[br["kind"].isin(["fee", "cost"])].assign(a=lambda x: x["effect"].abs()).nlargest(
        5, "a")[["step", "effect"]]
    al = o["alerts_ex_ante"]
    al = al[al["severity"].isin(["red", "amber"])][["alert", "scope", "value", "severity"]]
    champs = ", ".join(f"{k}: {v['model']}" for k, v in o["champions"].items())
    ytd = o["monthly_summary"]
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>P2 executive one-pager · T4/2025</title>
<style>
body{{font-family:{_tokens()["font"]["family"]};color:{tk["text"]};background:#fff;margin:24px auto;
max-width:900px;padding:0 16px;line-height:1.4}}
h1{{font-size:1.4rem;margin:0}} h2{{font-size:1.05rem;margin:18px 0 6px}}
.badge{{display:inline-block;border:1px solid {tk["muted"]};border-radius:999px;padding:1px 10px;
font-size:.8rem;font-weight:600}}
.cards{{display:flex;gap:12px;flex-wrap:wrap}} .card{{flex:1 1 200px;background:{tk["surface"]};
border-radius:8px;padding:10px 14px}} .lbl{{font-size:.85rem;color:{tk["muted"]}}}
.val{{font-size:1.6rem;font-weight:700}} .sub{{font-size:.8rem}}
table{{border-collapse:collapse;width:100%;font-size:.85rem}}
th,td{{border-bottom:1px solid #ddd;padding:3px 6px;text-align:left}}
.note{{font-size:.8rem;color:{tk["muted"]}}}
@media print{{body{{margin:0}}}}
</style></head><body>
<h1>P2 · TPV, revenue and margin — closing quarter T4/2025</h1>
<span class="badge">SYNTHETIC DATA</span>
<p class="note">Data cut-off {meta["as_of"]} · forecast origin/last training day {meta["as_of"]} ·
horizon 92 days · champions ({html.escape(champs)}) · backtest {meta["backtest_version"]} ·
assumptions {meta["assumptions_version"]} · P1 seed {meta["p1_seed"]}. Revenue and margin are
estimates [TO VERIFY]. Generated by <code>cli report</code> from computed tables only.</p>
<div class="cards">{cards}</div>
<h2>TPV: actual vs plans (BRL)</h2>{_bars(bars)}
<h2>Largest arithmetic effects, budget v1 → actual (contribution)</h2>
{_table(br, {"effect": "{:+,.0f}"})}
<h2>Ex-ante alerts at the cut-off (amber/red)</h2>
{_table(al, {"value": "{:+.1%}"})}
<h2>Monthly actual vs budget v1 (all countries)</h2>
{_table(ytd.groupby("month")[["actual_tpv", "budget_v1_tpv"]].sum().reset_index(),
        {"actual_tpv": "{:,.0f}", "budget_v1_tpv": "{:,.0f}"})}
<p class="note">Budget v1 is labelled as-of 2024-12-31 but anchored on January 2025 data.
Scenarios are business assumptions, not statistical intervals; bridges show
arithmetic differences, not causes. One quarter of synthetic data: not evidence of real-world
performance.</p></body></html>"""
